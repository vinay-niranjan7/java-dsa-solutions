/**
 * Definition for singly-linked list.
 * class ListNode {
 *     int val;
 *     ListNode next;
 *     ListNode(int x) {
 *         val = x;
 *         next = null;
 *     }
 * }
 */
public class Solution {
    public ListNode detectCycle(ListNode head) {
        ListNode tmp=head;
        ArrayList<ListNode> list= new ArrayList<>();
        while(tmp!=null){
            if(list.contains(tmp)) return tmp;
            list.add(tmp);
            tmp=tmp.next;
        }
        return null;
    }
}

