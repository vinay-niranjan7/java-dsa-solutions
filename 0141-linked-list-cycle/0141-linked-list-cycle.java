/**
 * Definition for singly-linked list.
 * class ListNode {
 *     int val;
 *     ListNode next;
 *     ListNode(int x) {
 *         val = x;
 *         next = null;
 *     }
 * }
 */
public class Solution {
    public boolean hasCycle(ListNode head) {
        ListNode tmp = head;
        ArrayList<ListNode> list = new ArrayList<>();

        while (tmp != null) {
            if (list.contains(tmp)) {
                return true;
            }
            list.add(tmp);
            tmp = tmp.next;
        }
        return false;
    }
}

